"""wp-admin colour scheme "Harrow Hub": WordPress's own Default scheme (wp-admin/css/colors/modern/colors.css) with
its blue turned into the Hub red (#DF2028, --ho-red in the theme's hub.css). Every blue shade keeps its lightness
relative to the main blue, so hovers and highlights stay in step. Run again after a WordPress update:

    python tools/build_admin_colors.py

Writes wp-local/hub/wp-content/themes/harrow-hub/admin/hub-admin-colors.css (registered in inc/admin/admin-colors.php).
"""
import colorsys, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "wp-local/hub/wp-admin/css/colors/modern/colors.css"
OUT = ROOT / "wp-local/hub/wp-content/themes/harrow-hub/admin/hub-admin-colors.css"
BLUE, RED = (0x38, 0x58, 0xE9), (0xDF, 0x20, 0x28)

def hls(rgb):
    return colorsys.rgb_to_hls(*(c / 255 for c in rgb))

BH, BL, BS = hls(BLUE)
RH, RL, RS = hls(RED)

def to_red(rgb):
    h, l, s = hls(rgb)
    if s < 0.25 or not (0.55 < h < 0.75):          # greys, whites and the error red stay as they are
        return None
    if all(abs(a - b) < 1 for a, b in zip(rgb, BLUE)):
        return RED
    l2 = min(0.97, max(0.05, RL + (l - BL)))
    s2 = min(1.0, s * RS / BS)
    return tuple(round(c * 255) for c in colorsys.hls_to_rgb(RH, l2, s2))

def hex_sub(m):
    v = m.group(1)
    rgb = tuple(int(v[i:i + 2], 16) for i in (0, 2, 4)) if len(v) == 6 else tuple(int(c * 2, 16) for c in v)
    new = to_red(rgb)
    return m.group(0) if new is None else "#%02x%02x%02x" % new + m.group(2)

def rgb_sub(m):
    rgb = tuple(float(x) for x in m.group(1).split(","))
    new = to_red(rgb)
    return m.group(0) if new is None else "rgb(%d, %d, %d)" % new

css = SRC.read_text(encoding="utf-8")
css = re.sub(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})([^0-9a-fA-F])", hex_sub, css)
css = re.sub(r"rgb\(([\d.]+,\s*[\d.]+,\s*[\d.]+)\)", rgb_sub, css)

def darker(rgb, amount):   # Sass darken(): lightness down by amount
    h, l, s = hls(rgb)
    return tuple(round(c * 255, 4) for c in colorsys.hls_to_rgb(h, max(0, l - amount), s))
d10, d20 = darker(RED, 0.05), darker(RED, 0.10)
fmt = lambda c: ", ".join(("%g" % x) for x in c)
head = f"""/*! Generated by tools/build_admin_colors.py from WordPress's Default admin scheme: the blue is the Hub red. */
body.admin-color-hub {{
  --wp-admin-theme-color: #df2028;
  --wp-admin-theme-color--rgb: {fmt(RED)};
  --wp-admin-theme-color-darker-10: rgb({fmt(d10)});
  --wp-admin-theme-color-darker-10--rgb: {fmt(d10)};
  --wp-admin-theme-color-darker-20: rgb({fmt(d20)});
  --wp-admin-theme-color-darker-20--rgb: {fmt(d20)};
  --wp-admin-border-width-focus: 2px;
}}
@media (min-resolution: 192dpi) {{
  body.admin-color-hub {{
    --wp-admin-border-width-focus: 1.5px;
  }}
}}

"""
OUT.write_text(head + css.replace("/*! This file is auto-generated */\n", ""), encoding="utf-8", newline="\n")
left = [c for c in re.findall(r"#[0-9a-fA-F]{6}\b", css) if to_red(tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)))]
print(f"written {OUT.relative_to(ROOT)}; blue left: {len(left)}")
